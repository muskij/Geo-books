/** @returns {Promise<{ok:boolean, pending?:boolean, reason?:string}>} */
export async function checkSubjectAccess(user, kind, courseKey) {
  let isAdmin = false;
  try { isAdmin = (await user.getIdTokenResult()).claims.admin === true; } catch (e) { /* treat as non-admin */ }
  if (isAdmin) return { ok: true };

  if (kind === 'tutor') {
    try {
      const course = await getDoc(doc(db, 'tutorCourses', courseKey));
      if (course.exists() && course.data().tutorId === user.uid) return { ok: true };
      const purchase = await getDoc(doc(db, 'tutorPurchases', `${user.uid}_${courseKey}`));
      if (purchase.exists() && purchase.data().status === 'verified') return { ok: true };
      if (purchase.exists()) return { ok: false, pending: true, reason: 'Your enrollment is recorded and awaiting admin verification. Check back shortly.' };
    } catch (e) { console.error('Tutor access check failed:', e); }
    return { ok: false, reason: 'Enroll in this tutor course to view its lessons.' };
  }

  try {
    const snap = await getDoc(doc(db, 'users', user.uid));
    const sub = snap.exists() ? snap.data().subscription : null;
    if (sub && ['UNIVERSITY_PASS_30', 'UNIVERSITY_PASS_70'].includes(sub.tier) && sub.verified === true && sub.status === 'active') return { ok: true };
  } catch (e) { console.error('University access check failed:', e); }
  return { ok: false, reason: 'You need an active University Pass to view these lessons.' };
}

/** All topics of a course, ordered. Sorted client-side so no composite index is required. */
export async function loadCourseTopics(kind, courseKey) {
  const k = KIND[kind];
  const snap = await getDocs(query(collection(db, k.collection), where(k.courseField, '==', courseKey)));
  return snap.docs.map((d) => ({ id: d.id, ...d.data() }))
    .sort((a, b) => (Number(a.topicNumber) || 0) - (Number(b.topicNumber) || 0));
}

export function readProgress(uid, topicId) {
  try { return new Set(JSON.parse(localStorage.getItem(`${PROGRESS_KEY_PREFIX}${uid || ''}:${topicId}`) || '[]')); }
  catch (e) { return new Set(); }
}
export function writeProgress(uid, topicId, set) {
  try { localStorage.setItem(`${PROGRESS_KEY_PREFIX}${uid || ''}:${topicId}`, JSON.stringify([...set])); }
  catch (e) { console.warn('Could not save progress locally:', e); }
}

