// Link normalisers — same behaviour as MedPhysio's lib/links.js.
// ---------------------------------------------------------------------------
export function normalizeYouTube(input) {
  const url = String(input || '').trim();
  if (!url) return null;
  const patterns = [
    /youtu\.be\/([a-zA-Z0-9_-]{6,})/,
    /youtube(?:-nocookie)?\.com\/watch\?(?:.*&)?v=([a-zA-Z0-9_-]{6,})/,
    /youtube(?:-nocookie)?\.com\/embed\/([a-zA-Z0-9_-]{6,})/,
    /youtube(?:-nocookie)?\.com\/shorts\/([a-zA-Z0-9_-]{6,})/
  ];
  for (const re of patterns) {
    const m = url.match(re);
    if (m) return { id: m[1], url: `https://youtu.be/${m[1]}`, embedUrl: `https://www.youtube-nocookie.com/embed/${m[1]}?rel=0` };
  }
  return null;
}

export function normalizeDrive(input) {
  const m = String(input || '').trim().match(/drive\.google\.com\/file\/d\/([a-zA-Z0-9_-]+)/);
  if (!m) return null;
  return { url: `https://drive.google.com/file/d/${m[1]}/view?usp=sharing`, embedUrl: `https://drive.google.com/file/d/${m[1]}/preview` };
}

