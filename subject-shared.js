/** Authenticated POST to server.js; throws Error(message) on failure. */
export async function apiPost(path, body) {
  const user = auth.currentUser;
  if (!user) throw new Error('You must be signed in.');
  const idToken = await user.getIdToken();
  const res = await fetch(`${API_BASE_URL}${path}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${idToken}` },
    body: JSON.stringify(body || {})
  });
  let data = null;
  try { data = await res.json(); } catch (e) { /* non-JSON error body */ }
  if (!res.ok) throw new Error((data && data.error) || `Server error (${res.status})`);
  return data;
}

// ---------------------------------------------------------------------------
// HTML safety. Lesson HTML is generated by AI and rendered with innerHTML, so
// it is re-sanitised here on every render against an allow-list of tags and
// the exact MedPhysio component class names (the server already did the same
// when generating — this is defence in depth, and also covers hand-edited HTML
// saved from the admin review step).
// ---------------------------------------------------------------------------
const ALLOWED_TAGS = new Set(['H3', 'H4', 'P', 'STRONG', 'EM', 'B', 'I', 'UL', 'OL', 'LI', 'DIV', 'SPAN', 'SMALL', 'BR', 'SUP', 'SUB']);
const ALLOWED_CLASSES = new Set([
  'mini-section-title', 'requirement-pills', 'cause-grid', 'morph-grid', 'function-list',
  'epo-flow', 'clinical-box', 'mini-summary', 'exam-summary'
]);

export function sanitizeLessonHtml(html) {
  const doc = new DOMParser().parseFromString(`<body>${String(html || '')}</body>`, 'text/html');
  const walk = (node) => {
    [...node.childNodes].forEach((child) => {
      if (child.nodeType === 3) return;                 // text
      if (child.nodeType !== 1) { child.remove(); return; } // comments etc.
      if (!ALLOWED_TAGS.has(child.tagName)) {
        // Drop dangerous elements entirely; unwrap harmless unknown ones.
        if (/^(SCRIPT|STYLE|IFRAME|OBJECT|EMBED|SVG|MATH|FORM|LINK|META|TEMPLATE)$/.test(child.tagName)) { child.remove(); return; }
        walk(child);
        child.replaceWith(...child.childNodes);
        return;
      }
      const keep = (child.getAttribute('class') || '').split(/\s+/).filter((c) => ALLOWED_CLASSES.has(c));
      [...child.attributes].forEach((a) => child.removeAttribute(a.name));
      if (keep.length) child.setAttribute('class', keep.join(' '));
      walk(child);
    });
  };
  walk(doc.body);
  return doc.body.innerHTML;
}

export const stripTags = (html) =>
  String(html || '').replace(/<[^>]*>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();

export const estimateReadMinutes = (html) =>
  Math.max(1, Math.round(stripTags(html).split(/\s+/).filter(Boolean).length / 200));

